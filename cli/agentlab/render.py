def go_literal(text):
    """Escape for Go's RE2 inside a Traefik rule: only regex metacharacters, so the result stays valid RE2."""
    return ''.join('\\' + ch if ch in '\\.+*?()|[]{}^$' else ch for ch in text)


def edge(cfg):
    """Traefik's dynamic config, in two passes (docs/architecture.md, "Edge: two passes"). Pass 1 deletes every
    client-sent identity header, stamps which site was asked for, asks tinyauth (in that mode) and the gate, and
    forwards to pass 2 with the gate's answer; pass 2 only follows X-Agentlab-Site / X-Agentlab-Agent, which nothing
    outside the edge can set. Routing pass 2 on the site header rather than Host() is what lets tailscale mode serve
    agents and hub on one MagicDNS name."""
    auth = cfg['auth']
    mode, ingress = auth['mode'], auth['ingress']
    routers, services, middlewares = {}, {}, {}
    pass1 = ['ingress', 'websecure'] if ingress == 'public' else ['ingress']

    def route(name, rule, service, chain, entrypoints, priority=None):
        r = {'entryPoints': entrypoints, 'rule': rule, 'service': service}
        if chain:
            r['middlewares'] = chain
        if priority is not None:
            r['priority'] = priority
        if ingress == 'public' and 'websecure' in entrypoints:
            r['tls'] = {'certResolver': 'le'}
        routers[name] = r

    def lb(name, url):
        services[name] = {'loadBalancer': {'servers': [{'url': url}], 'passHostHeader': True}}

    def strip(name, site=None):
        """Delete what a client could forge ('' removes a header); the site header is ours, set after deleting."""
        forged = CLIENT_HEADERS + (TINYAUTH_HEADERS if mode == 'tinyauth' else [])
        headers = dict.fromkeys(forged, '')
        if site:
            headers['X-Agentlab-Site'] = site
        middlewares[name] = {'headers': {'customRequestHeaders': headers}}
        return name

    middlewares['gate'] = {
        'forwardAuth': {
            'address': 'http://gate:8080/verify',
            'trustForwardHeader': True,
            'authResponseHeaders': IDENTITY,
        }
    }
    checks = ['gate']
    if mode == 'tinyauth':
        middlewares['tinyauth'] = {
            'forwardAuth': {
                'address': 'http://tinyauth:3000/api/auth/traefik',
                'trustForwardHeader': True,
                'authResponseHeaders': TINYAUTH_HEADERS,
            }
        }
        checks = ['tinyauth', 'gate']

    # ---- pass 1
    lb('pass2', f'http://{ROUTED}')
    sites = {'agent': cfg['domain'], 'hub': cfg['hub_domain'], 'coolify': cfg['coolify_domain']}
    for site_name, host in sites.items():
        if not host:
            continue
        entry, rule = pass1, f'Host(`{host}`)'
        if ingress == 'tailscale':
            # One MagicDNS name for agents and hub: `tailscale serve` maps 443 and hub_port to their own entrypoints.
            entry = ['hubingress'] if site_name == 'hub' else ['ingress']
            rule = 'PathPrefix(`/`)'
            if site_name == 'coolify':
                continue
        route(f'in-{site_name}', rule, 'pass2', [strip(f'site-{site_name}', site_name), *checks], entry)
    if mode == 'tinyauth':
        lb('tinyauth', 'http://tinyauth:3000')
        route('in-tinyauth', f'Host(`{auth["tinyauth"]["domain"]}`)', 'tinyauth', [strip('strip')], pass1)
    for a in cfg['agents']:
        lb(f'{a["id"]}-t3', f'{a["upstream"]}:{PORTS["t3"]}')
        if a['pair_host']:
            # Apps can't do a browser sign-in: this host goes straight to T3, which accepts only paired sessions.
            route(f'pair-{a["id"]}', f'Host(`{a["pair_host"]}`)', f'{a["id"]}-t3', [strip('strip')], pass1)

    # ---- pass 2
    def site(name):
        return f'Header(`X-Agentlab-Site`, `{name}`)'

    middlewares['strip-accounts'] = {'stripPrefix': {'prefixes': ['/_agentlab/accounts']}}
    middlewares['strip-browser'] = {'stripPrefix': {'prefixes': ['/_agentlab/browser']}}
    lb('gate', 'http://gate:8080')
    menu = '(Path(`/_agentlab`) || Path(`/_agentlab/`) || PathPrefix(`/_agentlab/view/`))'
    route('menu', f'{site("agent")} && {menu}', 'gate', [], ['routed'], PRIORITY['menu'])
    route(
        'no-agent', f'{site("agent")} && Header(`X-Agentlab-Agent`, `gate`)', 'gate', [], ['routed'], PRIORITY['gate']
    )
    for a in cfg['agents']:
        aid = a['id']
        for tool in ('accounts', 'browser', 'terminal'):
            lb(f'{aid}-{tool}', f'{a["upstream"]}:{PORTS[tool]}')
        lb(f'{aid}-files', f'http://files-{aid}:80')
        mine = f'{site("agent")} && Header(`X-Agentlab-Agent`, `{aid}`)'
        for tool in ('accounts', 'browser', 'terminal', 'files'):
            # ttyd (--base-path) and File Browser (baseURL) serve under their prefix; the others want it gone.
            strip_prefix = [f'strip-{tool}'] if tool in ('accounts', 'browser') else []
            route(
                f'{aid}-{tool}',
                f'{mine} && PathPrefix(`/_agentlab/{tool}`)',
                f'{aid}-{tool}',
                strip_prefix,
                ['routed'],
                PRIORITY['tool'],
            )
        route(f'{aid}-t3', mine, f'{aid}-t3', [], ['routed'], PRIORITY['t3'])
    lb('hub', 'http://hub:8080')
    route('hub', site('hub'), 'hub', [], ['routed'])
    if cfg['coolify_domain'] and ingress != 'tailscale':
        lb('coolify', 'http://host.docker.internal:8000')
        route('coolify', site('coolify'), 'coolify', [], ['routed'])
    # Nothing else matches: Traefik answers 404 itself, in both passes.
    return {'http': {'routers': routers, 'services': services, 'middlewares': middlewares}}


def firewall(cfg):
    """nftables rules for agentlab-firewall.service. An agent may answer the edge, gate, hub and its companions but
    never open a connection to them, to another agent or to the host: that is what lets the gate and hub trust
    headers set by tailscale serve / tinyauth, and keeps an agent away from Coolify, SSH and the Docker API.
    Docker's embedded DNS answers inside the container's own namespace, so DNS needs no rule; the internet stays
    open. (ufw can't do this: Docker's forwarding bypasses ufw's chains.)"""
    ips = [config.agent_ip(a) for a in cfg['agents']]
    elements = f'        elements = {{ {", ".join(ips)} }}\n' if ips else ''
    return (
        f'# {GENERATED}\n'
        'add table inet agentlab\n'
        'delete table inet agentlab\n'
        'table inet agentlab {\n'
        '    set agents {\n'
        '        type ipv4_addr\n'
        f'{elements}'
        '    }\n'
        '    chain input {\n'
        '        type filter hook input priority filter - 1; policy accept;\n'
        '        ip saddr @agents ct state established,related accept\n'
        '        ip saddr @agents counter drop comment "agent to host"\n'
        '    }\n'
        '    chain forward {\n'
        '        type filter hook forward priority filter - 1; policy accept;\n'
        f'        ip saddr @agents ip daddr {AGENTLAB_NET} ct state new counter drop comment "agent to cluster"\n'
        '    }\n'
        '}\n'
    )


def all_files(cfg):
    """{relative path: text} of every rendered file."""
    files = {
        'cluster.json': config.to_json(cfg),
        'edge/dynamic.yml': yaml.dump(edge(cfg), GENERATED),
        'firewall/agentlab.nft': firewall(cfg),
    }
    by_id = {a['id']: a for a in cfg['agents']}
    by_name = {c['name']: c for c in cfg['companions']}
    for stack, (kind, key) in stacks(cfg).items():
        if kind == 'core':
            body = core(cfg)
        elif kind == 'agent':
            body = agent(cfg, by_id[key])
        else:
            body = companion(cfg, by_name[key])
        files[f'compose/{stack}/docker-compose.yml'] = yaml.dump(stamped(body), f'{stack}. {GENERATED}')
    return files


RENDERED_LABEL = 'agentlab.rendered'


def stamped(body):
    """Every service labelled with the digest of the stack as rendered, so a deploy can tell its own containers from
    ones an earlier run left behind (Coolify and Compose recreate only what changed, so creation times can't)."""
    digest = hashlib.sha256(yaml.dump(body, '').encode()).hexdigest()[:16]
    for service in body.get('services', {}).values():
        service['labels'] = {**service.get('labels', {}), RENDERED_LABEL: digest}
    return body


def rendered_digest(text):
    """The digest stamped into a rendered compose file, or '' (a file rendered before stamping existed)."""
    m = re.search(rf'{re.escape(RENDERED_LABEL)}: "?(\w+)', text)
    return m.group(1) if m else ''
