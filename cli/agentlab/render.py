CLOUDFLARED = 'cloudflare/cloudflared:2026.10.1'
PORTS = {'t3': 3773, 'accounts': 8790, 'browser': 6080, 'terminal': 7681}
FILEBROWSER = 'gtstef/filebrowser:2.0.2-stable'
FILES_BASE = '/_agentlab/files'
SDK_IN_AGENT = '/opt/android-sdk'
GENERATED = 'GENERATED by agentctl from /etc/agentlab/cluster.toml: edit that, then `agentctl apply`.'
EDGE_NETWORK, EDGE_BRIDGE, EDGE_SUBNET = 'agentlab-edge', 'al-edge', '10.207.0.0/24'
# Fixed, below the network's .128/25 pool for everything else, so the tunnel container can name it in extra_hosts.
EDGE_IP = '10.207.0.2'
TUNNEL_TOKEN_DIR = 'secrets/cloudflared'  # under <data>: a copy of the tunnel token readable by cloudflared's uid
