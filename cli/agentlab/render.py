# Pass-1 entrypoints: `ingress` is what cloudflared / tailscale serve reach on host loopback; `hubingress` is the
# hub's own port in tailscale mode (one MagicDNS name, two ports); `websecure` exists only for public ingress.
INGRESS_PORT, HUB_INGRESS_PORT, ROUTED = 8088, 8090, '127.0.0.1:8089'
IDENTITY = ['X-Agentlab-User', 'X-Agentlab-Admin', 'X-Agentlab-Agent']
CLIENT_HEADERS = [*IDENTITY, 'X-Agentlab-Site', 'X-Agentlab-Target']
TINYAUTH_HEADERS = ['Remote-User', 'Remote-Email', 'Remote-Name', 'Remote-Groups']

# Pass-2 priorities: an agent's tools beat the gate's menu, which beats T3's catch-all path.
PRIORITY = {'tool': 500, 'menu': 400, 't3': 200, 'gate': 100}


def network(agent_id):
    return f'agentlab-{agent_id}'


def bridge(agent_id):
    """The host interface of an agent's network (Linux caps names at 15 characters)."""
    name = f'al-{agent_id}'
    return name if len(name) <= 15 else 'al-' + hashlib.sha1(agent_id.encode()).hexdigest()[:12]


def stacks(cfg):
    """{stack name: (kind, key)} in deploy order: the core first, so the edge exists when agents come up."""
    out = {'agentlab-core': ('core', None)}
    out.update({f'agentlab-agent-{a["id"]}': ('agent', a['id']) for a in cfg['agents']})
    out.update({f'agentlab-companion-{c["name"]}': ('companion', c['name']) for c in cfg['companions']})
    return out


def _image(cfg, name):
    """Locally built images must never be pulled (there is nothing to pull them from)."""
    out = {'image': images.ref(cfg, name)}
    if images.local(cfg):
        out['pull_policy'] = 'never'
    return out


def _external(name):
    return {name: {'external': True, 'name': name}}


def public_hosts(cfg):
    """Every hostname people or apps reach; the tunnel, DNS and certificates cover exactly these."""
    hosts = [
        cfg['domain'],
        cfg['hub_domain'],
        cfg['coolify_domain'],
        cfg['auth']['tinyauth']['domain'],
        *[a['pair_host'] for a in cfg['agents']],
    ]
    return list(dict.fromkeys(h for h in hosts if h))


def private_names(cfg):
    """The names Cloudflare routes privately to this cluster (network = "private")."""
    if not config.private_network(cfg):
        return []
    return [h for h in (cfg['domain'], cfg['hub_domain'], cfg['coolify_domain']) if h]


def edge_service(cfg):
    data, auth = cfg['data'], cfg['auth']
    private = config.private_network(cfg)
    # Private hostname routes make cloudflared connect to each name on port 80, the plain-HTTP port Access issues its
    # token on without Gateway TLS decryption; the tunnel container reaches the edge directly on that port, so it
    # needs no host port (Coolify's proxy may already hold 80).
    ingress = 80 if private else INGRESS_PORT
    command = [
        f'--entrypoints.ingress.address=:{ingress}',
        f'--entrypoints.routed.address={ROUTED}',  # pass 2: only the edge itself can reach it
        '--providers.file.directory=/etc/traefik/dynamic',
        '--providers.file.watch=true',
        '--api.dashboard=false',
        '--global.sendanonymoususage=false',
        '--log.level=WARN',
    ]
    ports = [f'127.0.0.1:{INGRESS_PORT}:{ingress}']
    volumes = [f'{data}/rendered/edge:/etc/traefik/dynamic:ro']
    if auth['ingress'] == 'tailscale':
        command.append(f'--entrypoints.hubingress.address=:{HUB_INGRESS_PORT}')
        ports.append(f'127.0.0.1:{HUB_INGRESS_PORT}:{HUB_INGRESS_PORT}')
    if auth['ingress'] == 'public':
        command += [
            '--entrypoints.web.address=:80',
            '--entrypoints.websecure.address=:443',
            '--entrypoints.web.http.redirections.entrypoint.to=websecure',
            '--certificatesresolvers.le.acme.httpchallenge.entrypoint=web',
            f'--certificatesresolvers.le.acme.email={auth["admins"][0]}',
            '--certificatesresolvers.le.acme.storage=/acme/acme.json',
        ]
        ports += ['80:80', '443:443']
        volumes.append(f'{data}/edge-acme:/acme')
    return {
        'image': TRAEFIK,
        'restart': 'unless-stopped',
        'command': command,
        'ports': ports,
        'volumes': volumes,
        'extra_hosts': ['host.docker.internal:host-gateway'],
        # The private names as aliases: Gateway sends their DNS lookups through the tunnel to cloudflared, which asks
        # Docker's DNS (not its hosts file); the aliases are what answer them with the edge
        'networks': {EDGE_NETWORK: {'aliases': ['edge', *private_names(cfg)], 'ipv4_address': EDGE_IP}},
        'mem_limit': '256m',
    }


def cloudflared_service(cfg):
    """The tunnel for private names, next to the edge: it resolves each name to the edge's fixed address and joins
    no agent network. The token stays out of the compose text (Coolify shows that): a file only its uid reads."""
    return {
        'image': CLOUDFLARED,
        'restart': 'unless-stopped',
        'command': ['tunnel', '--metrics', '127.0.0.1:20241', 'run', '--token-file', '/etc/cloudflared/token'],
        'volumes': [f'{cfg["data"]}/{TUNNEL_TOKEN_DIR}:/etc/cloudflared:ro'],
        'extra_hosts': [f'{h}:{EDGE_IP}' for h in private_names(cfg)],
        'networks': {EDGE_NETWORK: {'aliases': ['cloudflared']}},
        'healthcheck': {
            'test': ['CMD', 'cloudflared', 'tunnel', '--metrics', '127.0.0.1:20241', 'ready'],
            'interval': '30s',
            'timeout': '5s',
            'retries': 3,
            'start_period': '20s',
        },
        'mem_limit': '128m',
    }


def people(cfg):
    """Everyone allowed to sign in by name: the agent owners and the admins ([auth] allow_domains adds whole email
    domains on top; people there without an agent get the gate's "no agent yet" page)."""
    return sorted({a['owner'] for a in cfg['agents']} | set(cfg['auth']['admins']))


def tinyauth_whitelist(cfg):
    """tinyauth's OAuth whitelist: the people by name plus one /regex/ entry per allowed email domain."""
    domains = [r'/^[^@]+@' + re.escape(d) + '$/' for d in cfg['auth']['allow_domains']]
    return ','.join(people(cfg) + domains)


def tinyauth_service(cfg):
    t = cfg['tinyauth']
    return {
        'image': t['image'],
        'restart': 'unless-stopped',
        'environment': {
            'APP_URL': f'https://{t["domain"]}',
            'SECRET_FILE': '/secrets/tinyauth-secret.txt',
            'GOOGLE_CLIENT_ID_FILE': '/secrets/google-client-id',
            'GOOGLE_CLIENT_SECRET_FILE': '/secrets/google-client-secret',
            'OAUTH_WHITELIST': tinyauth_whitelist(cfg),  # global allow-list only: per-agent access stays with the gate
            'COOKIE_SECURE': 'true',
            'APP_TITLE': cfg['name'],
        },
        'volumes': [
            f'{cfg["data"]}/secrets/tinyauth-secret.txt:/secrets/tinyauth-secret.txt:ro',
            f'{t["google_client_id_file"]}:/secrets/google-client-id:ro',
            f'{t["google_client_secret_file"]}:/secrets/google-client-secret:ro',
        ],
        'networks': {EDGE_NETWORK: {'aliases': ['tinyauth']}},
        'mem_limit': '128m',
    }


def core(cfg):
    data = cfg['data']
    mounts = [f'{data}/rendered:/etc/agentlab:ro']
    none = cfg['auth']['mode'] == 'none'
    gate_env = {'AGENTLAB_CLUSTER': '/etc/agentlab/cluster.json', 'TZ': cfg['timezone']}
    if none:
        gate_env['GATE_ALLOW_NONE'] = '1'  # local testing only: the edge is loopback-bound either way
    services = {
        'edge': edge_service(cfg),
        'gate': {
            **_image(cfg, 'gate'),
            'restart': 'unless-stopped',
            'environment': gate_env,
            'volumes': mounts,
            'networks': {EDGE_NETWORK: {'aliases': ['gate']}},
            'mem_limit': '128m',
        },
        'hub': {
            **_image(cfg, 'hub'),
            'restart': 'unless-stopped',
            'environment': {
                'HUB_CONFIG': '/etc/agentlab/cluster.json',
                'TZ': cfg['timezone'],
                'PYTHONUNBUFFERED': '1',
                **({'HUB_ALLOW_NONE': '1'} if none else {}),
            },
            'volumes': [
                *mounts,
                f'{data}/rendered:/rendered:ro',  # the Configs screen shows the rendered stacks
                f'{data}/hub/data:/data',  # its own state (phone pushes, display settings): on the host, in backups
                f'{data}/hub/watch:/watch',  # the host watcher's output, and requests/ for its buttons
                f'{data}/companions:/companions',  # what companions publish; the hub writes their settings.json
                f'{data}/secrets:/secrets',  # the Secrets screen
                # One mount per agent, wherever its storage puts it; writable because SQLite readers need -shm.
                *[f'{a["path"]}:/agents/{a["id"]}' for a in cfg['agents']],
            ],
            'extra_hosts': ['host.docker.internal:host-gateway'],  # a Bark server on the host, say
            'networks': {EDGE_NETWORK: {'aliases': ['hub']}},
            'mem_limit': '512m',
        },
    }
    if cfg['bark']['url']:
        # Phone pushes: where the hub posts them, and the address the phone app registers with.
        services['hub']['environment']['BARK_URL'] = cfg['bark']['url']
        services['hub']['environment']['BARK_PUBLIC'] = cfg['bark']['public'] or cfg['bark']['url']
    extra = cfg['hub']['extra_secrets']
    if extra['folder']:
        # Other secrets on this host, shown (admins only) as their own group; the watcher applies their map.
        hub = services['hub']
        hub['volumes'].append(f'{extra["folder"]}:/extra-secrets')
        hub['environment'].update(HUB_EXTRA_SECRETS='/extra-secrets', HUB_EXTRA_SECRETS_LABEL=extra['label'])
        if extra['map']:
            hub['volumes'].append(f'{extra["map"]}:/extra-secrets-map.json:ro')
            hub['environment']['HUB_EXTRA_SECRETS_MAP'] = '/extra-secrets-map.json'
    if cfg['hub']['publish']:
        services['hub']['ports'] = [f'{cfg["publish_address"]}:{cfg["hub"]["publish"]}:8080']
        # Requests on the published port skip the edge and the gate, so the hub treats them as this one person.
        services['hub']['environment']['HUB_PUBLISHED_OWNER'] = cfg['agents'][0]['owner']
    if cfg['auth']['mode'] == 'tinyauth':
        services['tinyauth'] = tinyauth_service(cfg)
    if config.private_network(cfg):
        services['cloudflared'] = cloudflared_service(cfg)
    return {'services': services, 'networks': _external(EDGE_NETWORK)}


def kvm_gid():
    try:
        return grp.getgrnam('kvm').gr_gid
    except KeyError:
        return None


def hub_address(cfg):
    """host[:port] people reach the hub on: its own name, or on Tailscale the shared MagicDNS name on hub_port."""
    auth = cfg['auth']
    if auth['ingress'] == 'tailscale' and cfg['hub_domain'] == cfg['domain']:
        return f'{cfg["hub_domain"]}:{auth["hub_port"]}'
    return cfg['hub_domain']


def agent(cfg, a):
    data, aid, home = cfg['data'], a['id'], a['path']
    svc = {
        **({'image': a['image']} if a['image'] else _image(cfg, 'agent')),
        'restart': 'unless-stopped',
        'hostname': a['hostname'],
        'env_file': [f'{data}/secrets/agents/{aid}.env'],
        'environment': {
            'AGENT_ID': aid,
            'AGENT_OWNER': a['owner'],
            'AGENTLAB_DOMAIN': cfg['domain'],
            'AGENTLAB_HUB_DOMAIN': hub_address(cfg),
            'AGENTLAB_PAIR_HOST': a['pair_host'],
            # Tools published on host ports: links (pairing, the hub, the browser view) use the host a page was
            # opened on plus that port
            'AGENTLAB_PUBLISHED': ','.join(f'{t}={p}' for t, p in sorted(a['publish'].items())),
            'AGENTLAB_PUBLISHED_HUB': str(cfg['hub']['publish'] or ''),
            'AGENTLAB_AUTH_MODE': cfg['auth']['mode'],
            'AGENTLAB_ISOLATION': cfg['isolation'],  # which Docker engine the agent runs (image: agent-dockerd)
            # Coolify starts the container on a network of its own before agentlab takes it off; a download begun
            # on that address is stranded, so the entrypoint waits until this is the container's only address
            'AGENTLAB_WAIT_NETWORK': config.agent_ip(a) if cfg['deploy'] == 'coolify' else '',
            'ANDROID_ENABLED': '1' if cfg['android']['enabled'] else '',
            'ANDROID_SYSTEM_IMAGE': cfg['android']['system_image'],
            # agent-updater: how often to refresh T3/Claude/Codex, and what to do when T3 stays busy
            'AGENTLAB_UPDATE_HOURS': f'{cfg["updates"]["agent_tools_hours"]:g}',
            'AGENTLAB_UPDATE_WAIT_HOURS': f'{cfg["updates"]["wait_hours"]:g}',
            'AGENTLAB_ON_BUSY': cfg['updates']['on_busy'],
            'TZ': cfg['timezone'],
        },
        'volumes': [f'{home}/home:/home/agent', f'{home}/workspace:/workspace', f'{home}/linuxbrew:/home/linuxbrew'],
        'shm_size': '1gb',  # Chrome needs a large /dev/shm
        'devices': ['/dev/fuse', '/dev/net/tun'],
        'cgroup_parent': 'agentlab.slice',
        'mem_limit': a['memory'],
        'cpus': a['cpus'],
        # A fixed address: the firewall's rules for this agent are written against it.
        'networks': {network(aid): {'aliases': [f'agent-{aid}'], 'ipv4_address': config.agent_ip(a)}},
    }
    published = {t: p for t, p in a['publish'].items() if t != 'files'}
    if published:
        # One-person setups only (config refuses otherwise): these ports skip the edge and the gate.
        svc['ports'] = [f'{cfg["publish_address"]}:{port}:{PORTS[tool]}' for tool, port in published.items()]
    if cfg['isolation'] == 'sysbox':
        # Sysbox gives the container its own user namespace, so the agent's root dockerd inside works under the
        # default seccomp/AppArmor profiles; bind mounts are ID-mapped, so host files owned by uid 1000 stay uid 1000.
        svc['runtime'] = 'sysbox-runc'
    else:
        # Rootless Docker inside needs user namespaces: unconfined profiles + fuse/tun, but not privileged. One-person
        # hosts only (WSL can't run Sysbox).
        svc['security_opt'] = ['seccomp=unconfined', 'apparmor=unconfined', 'systempaths=unconfined']
    if cfg['android']['enabled']:
        svc['devices'].append('/dev/kvm')
        svc['volumes'].append(f'{data}/shared/android-sdk:{SDK_IN_AGENT}:ro')
        svc['environment']['ANDROID_SDK_ROOT'] = SDK_IN_AGENT
        gid = kvm_gid()
        if cfg['isolation'] == 'unconfined' and gid is not None:
            svc['group_add'] = [str(gid)]  # under Sysbox the udev rule makes /dev/kvm 0666 instead
    return {'services': {'agent': svc, 'files': files(cfg, a)}, 'networks': _external(network(aid))}


def files_data(cfg, a):
    """File Browser's config and database: the host's, not on the agent's disk, so the agent can't rewrite them."""
    return f'{cfg["data"]}/files/{a["id"]}'


def files(cfg, a):
    """The agent's file manager (File Browser) at /_agentlab/files/. No login of its own: the gate already decided
    who may see this agent. It runs as uid 1000 so files it writes stay the agent's."""
    svc = {
        'image': FILEBROWSER,
        'restart': 'unless-stopped',
        'user': '1000:1000',
        'environment': {'FILEBROWSER_CONFIG': '/home/filebrowser/data/config.yaml', 'TZ': cfg['timezone']},
        'volumes': [
            f'{a["path"]}/workspace:/workspace',
            f'{a["path"]}/home:/home-agent:ro',
            f'{files_data(cfg, a)}:/home/filebrowser/data',
        ],
        'networks': {network(a['id']): {'aliases': [f'files-{a["id"]}']}},
        'mem_limit': '256m',
    }
    if 'files' in a['publish']:
        svc['ports'] = [f'{cfg["publish_address"]}:{a["publish"]["files"]}:80']
    return svc


def files_config(cfg):
    """config.yaml for every agent's File Browser (they are all the same). Heavy folders are left out of the search
    index only; they still open."""
    rules = [{'folderName': n} for n in ('node_modules', '.git', '.next', 'dist', '.turbo')]
    return yaml.dump(
        {
            # Behind the edge on a subpath: trust its X-Forwarded-* so links and cookies resolve (the edge sets them).
            'http': {'port': 80, 'baseURL': FILES_BASE, 'trustProxyHeaders': True},
            'server': {
                'sources': [
                    {'path': '/workspace', 'name': 'workspace', 'config': {'defaultEnabled': True, 'rules': rules}},
                    {'path': '/home-agent', 'name': 'home', 'config': {'rules': rules}},
                ]
            },
            'auth': {'methods': {'noauth': True, 'password': {'enabled': False}}},
            'userDefaults': {'listing': {'showHidden': True}},
        },
        GENERATED,
    )


def agent_of(cfg, comp):
    return next(a for a in cfg['agents'] if a['id'] == comp['agent'])


def companion_checkout(cfg, comp):
    return f'{agent_of(cfg, comp)["path"]}/workspace/companions/{comp["name"]}'


